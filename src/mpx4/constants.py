from enum import IntEnum

MAGIC = b"MPX\x00"
VERSION = 4

MAX_HANDSHAKE_MESSAGE = 4096
MAX_FRAME_PAYLOAD = 32768
MAX_RECORD_SIZE = 65536
MAX_RECORDS_PER_KEY = 1 << 24
AEAD_TAG_LEN = 16


class HandshakeType(IntEnum):
    CLIENT_INIT = 0x01
    SERVER_INIT = 0x02
    CLIENT_FINISHED = 0x03
    SERVER_FINISHED = 0x04
    VERSION_NEGOTIATION = 0x05


class ParameterType(IntEnum):
    SESSION_ID = 0x01
    SESSION_ACTION = 0x02
    CARRIER_ID = 0x03
    CARRIER_GENERATION = 0x04
    CLIENT_NONCE = 0x05
    SERVER_NONCE = 0x06
    MAX_FRAME_PAYLOAD = 0x07
    MAX_RECORD_SIZE = 0x08
    MAX_STREAMS = 0x09
    SCHEDULER = 0x10
    PATH_CAPACITY = 0x11


class SessionAction(IntEnum):
    CREATE = 0
    JOIN = 1


class SchedulerID(IntEnum):
    AUTO = 0x00
    AGGREGATE = 0x01
    PROTECT = 0x02
    WEIGHTED = 0x03


class FrameType(IntEnum):
    PADDING = 0x00
    PING = 0x01
    PONG = 0x02
    CARRIER_CLOSE = 0x03
    SESSION_CLOSE = 0x04

    STREAM_OPEN = 0x10
    STREAM_OPEN_OK = 0x11
    STREAM_OPEN_REJECT = 0x12
    STREAM_DATA = 0x13
    TRANSMISSION_ACK = 0x14
    STREAM_CREDIT = 0x15
    STREAM_FIN = 0x16
    RESET_STREAM = 0x17
    STOP_SENDING = 0x18
    STREAM_CONSUMED = 0x19

    SESSION_CREDIT = 0x20
    CREDIT_PROBE = 0x21


class ErrorCode(IntEnum):
    NO_ERROR = 0x00
    INTERNAL_ERROR = 0x01
    PROTOCOL_VIOLATION = 0x02
    AUTHENTICATION_FAILED = 0x03
    VERSION_UNSUPPORTED = 0x04
    RESOURCE_LIMIT = 0x05
    SESSION_NOT_FOUND = 0x06
    SESSION_CONFLICT = 0x07
    STREAM_LIMIT = 0x08
    FLOW_CONTROL_ERROR = 0x09
    FRAME_ENCODING_ERROR = 0x0A
    SCHEDULER_MISMATCH = 0x0B
    CARRIER_CONFLICT = 0x0C
    UNSUPPORTED_PARAMETER = 0x0D
    STREAM_STATE_ERROR = 0x0E
    FINAL_SIZE_ERROR = 0x0F
    TRANSMISSION_ID_ERROR = 0x10
